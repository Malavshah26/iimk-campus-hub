// Generates a SAMPLE timetable for every section and year.
// Usage: npm run seed:timetable  (writes supabase/seed_timetable.sql)
// Replace with the official timetable on the Admin page (or by editing the SQL).
const SECS = ['A','B','C','D','E','F','G','H','LSM','FIN']
const CORE = [['MM2','Marketing Management II'],['CF','Corporate Finance'],['OM','Operations Management'],['DA','Data Analytics'],['OB','Organisational Behaviour'],['MA','Management Accounting'],['MAC','Macroeconomics'],['BC','Business Communication']]
const COURSES = {
  '1': CORE,
  '1LSM': [...CORE.slice(0,6),['PHE','Philosophy and Ethics'],['HOI','History of Ideas']],
  '1FIN': [...CORE.slice(0,6),['FMK','Financial Markets'],['FIA','Financial Instruments']],
  '2': [['PRM','Product Management'],['VAL','Valuation'],['DMK','Digital Marketing'],['SCA','Supply Chain Analytics'],['SCO','Strategy Consulting'],['B2B','B2B Marketing'],['FTK','FinTech'],['NEG','Negotiation']],
}
const q = s => "'" + String(s).replace(/'/g, "''") + "'"
const rows = []
for (const y of ['1','2']) for (const sec of SECS) {
  const L = y==='1' && (sec==='LSM'||sec==='FIN') ? COURSES['1'+sec] : COURSES[y]
  const si0 = SECS.indexOf(sec), seed = si0*5 + (y==='2'?3:0)
  for (let dow = 1; dow <= 6; dow++) {
    const k1 = (dow+seed)%6, k2 = (dow+seed+3)%6
    const slots = dow===6 ? [0,1] : [0,1,2,3,4,5].filter(i => i!==k1 && i!==k2)
    for (const si of slots) {
      const c = L[(dow*2+si*3+seed) % L.length]
      const room = y==='2' ? 'ER-'+((si+dow)%4+1) : sec==='LSM' ? 'CR-9' : sec==='FIN' ? 'CR-10' : 'CR-'+(si0+1)
      rows.push(`(${q(y)},${q(sec)},${dow},${si+1},${q(c[0])},${q(c[1])},${q(room)})`)
    }
  }
}
console.log('-- SAMPLE timetable generated by scripts/gen-timetable-seed.mjs. Run after seed.sql.')
console.log('insert into public.timetable (year, section, weekday, slot, course_code, course_name, room) values')
console.log(rows.join(',\n') + '\non conflict (year, section, weekday, slot) do nothing;')
